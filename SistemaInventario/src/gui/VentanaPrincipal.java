    private void btnRegistrarProductoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarProductoActionPerformed
        try {
            String nombre = txtNombreProducto.getText();
            double precio = Double.parseDouble(txtPrecioProducto.getText());
            int stock = Integer.parseInt(txtStockProducto.getText());
            double descuento = Double.parseDouble(txtDescuentoProducto.getText());
            
            // Instanciación del TDA
            miProducto = new logica.ProductoMayorista(nombre, precio, stock, descuento);
            
            javax.swing.JOptionPane.showMessageDialog(this, "¡Producto registrado!\nStock inicial: " + stock + "\nDescuento mayoreo: " + descuento + "%");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: Verifica que todos los datos numéricos estén correctos.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnRegistrarProductoActionPerformed

    private void btnRegistrarVentaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarVentaActionPerformed
       if (miProducto == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Primero debes registrar el producto a la izquierda.");
            return;
        }
        
        try {
            int cantidad = Integer.parseInt(txtCantidadProducto.getText());
            
            if (miProducto.vender(cantidad)) {
                
                // Calcula el total a pagar
                double total = miProducto.calcularTotalPagar(cantidad);
                
                txtTotalPagar.setText(String.format("$%.2f", total));
                
                if (cantidad >= 5) {
                    txtDescuentoAplicado.setText(miProducto.getPorcentajeDescuento() + "% Aplicado");
                } else {
                    txtDescuentoAplicado.setText("0% (Mínimo 5 unid.)");
                }
                
                txtStockProducto.setText(String.valueOf(miProducto.getStock()));
                
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Error: Solo quedan " + miProducto.getStock() + " unidades en stock.", "Sin stock", javax.swing.JOptionPane.WARNING_MESSAGE);
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: Ingresa una cantidad válida.");
        }
    }//GEN-LAST:event_btnRegistrarVentaActionPerformed

    private void btnCalcularResultadoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularResultadoActionPerformed
        if (miProducto == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Primero debes registrar el producto a la izquierda.");
            return;
        }
        
        try {
            double crecimiento = Double.parseDouble(txtPorcentajeCrecimiento.getText());
            int meses = Integer.parseInt(txtNumMeses.getText());
            double ventaInicial = 1000.0;
            
            double proyeccion = miProducto.proyectarVentasRecursivo(meses, ventaInicial, crecimiento);
            
            txtResultado.setText(String.format("$%.2f", proyeccion));
            
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: Verifica los datos de proyección.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCalcularResultadoActionPerformed

